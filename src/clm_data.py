"""
Financial CLM (Causal Language Modeling) Dataset for decoder-only pretraining.

Reads text corpus lines generated by the tokenizer pipeline and produces
(input_ids, labels) pairs for next-token prediction. No masking logic is
needed -- every token position provides a training signal.

Corpus line format:
    <bos> AMT_3 MERCH_1498 ... <sep> AMT_1 MERCH_42 ... <eos>

For causal LM:
    input_ids = full token sequence
    labels    = same as input_ids, with <pad> positions set to -100
                (HuggingFace convention: -100 = ignore in loss)

The model's forward pass handles the internal shift: it predicts
position i+1 from position i.

Entry point: ``build_bank_clm_dataset`` (named in the YAML as
``src/clm_data.py:build_bank_clm_dataset``). The tokenizer is *fitted*, so the
vocabulary is read from the ``vocab.json`` written next to the corpus.
"""

import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Union

import numpy as np
import torch
from torch.utils.data import Dataset

# Ensure tokenizer subpackage is importable when loaded by NeMo's
# file-path _target_ resolution (which bypasses normal package imports).
_src_dir = str(Path(__file__).resolve().parent)
if _src_dir not in sys.path:
    sys.path.insert(0, _src_dir)


class FinancialCLMDataset(Dataset):
    """PyTorch Dataset for causal language modeling on financial transactions.

    Compatible with NeMo AutoModel's ``StatefulDataLoader`` — returns dicts
    with ``input_ids`` and ``labels`` tensors, matching the interface expected
    by ``MaskedCrossEntropy`` loss and HuggingFace causal LM forward().
    """

    def __init__(
        self,
        sequences: List[List[int]],
        seq_length: int = 4096,
        pad_token_id: int = 0,
        loss_ignore_ids: Sequence[int] = (),
    ):
        self.sequences = sequences
        self.seq_length = seq_length
        self.pad_token_id = pad_token_id
        #: Token IDs that stay in the input but are not prediction targets
        #: (labels -100), e.g. ``<sep>``, which recurs at a fixed period and is
        #: free to predict once the model has seen a few transactions.
        self.loss_ignore_ids = np.asarray(sorted(set(loss_ignore_ids)), dtype=np.int64)

    def __len__(self) -> int:
        return len(self.sequences)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        tokens = self.sequences[idx]

        if len(tokens) > self.seq_length:
            tokens = tokens[: self.seq_length]

        input_ids = np.full(self.seq_length, self.pad_token_id, dtype=np.int64)
        input_ids[: len(tokens)] = tokens

        labels = np.full(self.seq_length, -100, dtype=np.int64)
        labels[: len(tokens)] = tokens
        if self.loss_ignore_ids.size:
            labels[np.isin(labels, self.loss_ignore_ids)] = -100

        # Explicit, because labels no longer mark exactly the real tokens: an
        # ignored token is -100 in labels but must still be attended to.
        attention_mask = np.zeros(self.seq_length, dtype=np.int64)
        attention_mask[: len(tokens)] = 1

        return {
            "input_ids": torch.from_numpy(input_ids),
            "labels": torch.from_numpy(labels),
            "attention_mask": torch.from_numpy(attention_mask),
        }


class BankMLMDataset(FinancialCLMDataset):
    """Masked-token prediction (``model.objective: mlm``): the same sequences, with
    some positions hidden.

    ``mask_unit="token"``: every field token is picked with probability
    ``mask_prob`` (BERT). ``"transaction"``: every transfer is picked with
    probability ``mask_prob`` and all its field tokens are hidden, so the model
    has to rebuild the transfer from the ones around it rather than from its
    other fields. ``<bos>``/``<eos>``/``<sep>``/``<pad>`` and
    ``loss_ignore_ids`` are never picked. A picked position becomes
    ``mask_token_id`` 80% of the time, a random field token 10%, and stays
    unchanged 10% (BERT); only picked positions carry a label (others -100).
    At least one position per sequence is picked.

    ``mask_seed=None`` draws new masks every time (training; torch's generator,
    which DataLoader seeds per worker). An integer fixes the mask of each
    sequence (validation: the same masks at every validation, so the loss
    curve is comparable step to step).
    """

    def __init__(
        self,
        sequences: List[List[int]],
        seq_length: int = 4096,
        pad_token_id: int = 0,
        loss_ignore_ids: Sequence[int] = (),
        *,
        mask_token_id: int,
        special_ids: Sequence[int],
        vocab_size: int,
        sep_token_id: int,
        mask_prob: float = 0.15,
        mask_unit: str = "token",
        mask_seed: Optional[int] = None,
    ):
        super().__init__(sequences, seq_length, pad_token_id, loss_ignore_ids)
        if mask_unit not in ("token", "transaction"):
            raise ValueError(f"mlm.mask_unit={mask_unit!r}; choose 'token' or 'transaction'")
        if not 0.0 < float(mask_prob) < 1.0:
            raise ValueError(f"mlm.mask_prob={mask_prob} must be between 0 and 1")
        self.mask_token_id = int(mask_token_id)
        self.sep_token_id = int(sep_token_id)
        self.mask_prob = float(mask_prob)
        self.mask_unit = mask_unit
        self.mask_seed = mask_seed
        never = set(int(i) for i in special_ids) | set(self.loss_ignore_ids.tolist())
        self._never = torch.tensor(sorted(never), dtype=torch.long)
        # Random replacements are drawn from the field tokens only.
        self._field_ids = torch.tensor(
            [i for i in range(int(vocab_size)) if i not in never], dtype=torch.long)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        item = super().__getitem__(idx)
        ids = item["input_ids"]
        gen = None
        if self.mask_seed is not None:
            gen = torch.Generator().manual_seed(int(self.mask_seed) * 1_000_003 + int(idx))

        can = (item["attention_mask"] == 1) & ~torch.isin(ids, self._never)
        if self.mask_unit == "token":
            picked = (torch.rand(ids.shape, generator=gen) < self.mask_prob) & can
        else:
            # Transfer number of every position: separators counted so far.
            txn = torch.cumsum((ids == self.sep_token_id).long(), dim=0)
            n_txn = int(txn.max()) + 1
            chosen = torch.rand(n_txn, generator=gen) < self.mask_prob
            picked = chosen[txn] & can
        if not bool(picked.any()) and bool(can.any()):
            # Never a sequence without a target (its loss would be undefined).
            choices = torch.nonzero(can).flatten()
            j = choices[torch.randint(len(choices), (1,), generator=gen)]
            if self.mask_unit == "transaction":
                txn = torch.cumsum((ids == self.sep_token_id).long(), dim=0)
                picked = (txn == txn[j]) & can
            else:
                picked[j] = True

        labels = torch.full_like(ids, -100)
        labels[picked] = ids[picked]
        r = torch.rand(ids.shape, generator=gen)
        new_ids = ids.clone()
        new_ids[picked & (r < 0.8)] = self.mask_token_id
        swap = picked & (r >= 0.8) & (r < 0.9)
        n_swap = int(swap.sum())
        if n_swap:
            pick = torch.randint(len(self._field_ids), (n_swap,), generator=gen)
            new_ids[swap] = self._field_ids[pick]
        item["input_ids"] = new_ids
        item["labels"] = labels
        return item


# ======================================================================
# Bank transfer schema  (fitted vocabulary)
# ======================================================================
#
# The bank tokenizer has no static vocabulary: amount bins and the frequency
# vocabularies are fitted on the training split. The corpus and the model must
# therefore use the vocabulary file written next to the corpus
# (``pipeline.save_vocab(...)`` in notebook 02), not a freshly constructed
# tokenizer.


def vocab_of(payload: Dict) -> Dict[str, int]:
    """``{token: id}`` from a parsed vocab.json (``{"vocab": {...}, ...}``) or a bare map.

    The one rule for this file: the data module and the trainer both use it.
    """
    return payload.get("vocab", payload)



class VocabTokenizer:
    """Minimal ``{token: id}`` tokenizer loaded from a JSON vocabulary file.

    Deliberately dependency-free (no cuDF): training ranks only need to map
    corpus token strings to IDs.
    """

    def __init__(self, vocab: Dict[str, int], special_tokens: Optional[Dict[str, str]] = None):
        self.vocab = {str(k): int(v) for k, v in vocab.items()}
        self.id_to_token = {v: k for k, v in self.vocab.items()}
        self.special_tokens = special_tokens or {
            "PAD": "<pad>", "BOS": "<bos>", "EOS": "<eos>",
            "SEP": "<sep>", "UNK": "<unk>",
        }
        self.pad_token_id = self.vocab.get("<pad>", 0)
        self.bos_token_id = self.vocab.get("<bos>", 1)
        self.eos_token_id = self.vocab.get("<eos>", 2)
        self.sep_token_id = self.vocab.get("<sep>", 3)
        self.unk_token_id = self.vocab.get("<unk>", 4)

    @classmethod
    def from_file(cls, path: Union[str, Path]) -> "VocabTokenizer":
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(
                f"Vocabulary file not found: {path}. Run notebook 02 "
                "(or scripts/build_bank_corpus.py) to fit the tokenizer and "
                "write vocab.json."
            )
        payload = json.loads(path.read_text())
        return cls(vocab_of(payload), payload.get("special_tokens"))

    @property
    def vocab_size(self) -> int:
        return max(len(self.vocab), max(self.vocab.values(), default=-1) + 1)

    def encode(self, text: str, max_length: Optional[int] = None) -> List[int]:
        tokens = text.split()
        if max_length:
            tokens = tokens[:max_length]
        unk = self.unk_token_id
        ids = [self.vocab.get(t, unk) for t in tokens]
        if max_length:
            ids.extend([self.pad_token_id] * (max_length - len(ids)))
        return ids

    def decode(self, token_ids: List[int]) -> str:
        return " ".join(
            tok for tok in (self.id_to_token.get(int(t)) for t in token_ids)
            if tok and tok != "<pad>"
        )


def build_bank_clm_dataset(
    data_path: str,
    vocab_path: str,
    seq_length: int = 4096,
    loss_ignore_tokens: Optional[Sequence[str]] = None,
    objective: str = "clm",
    mask_token_id: Optional[int] = None,
    mask_prob: float = 0.15,
    mask_unit: str = "token",
    mask_seed: Optional[int] = None,
    **kwargs,
) -> FinancialCLMDataset:
    """Entry point for the bank-transfer YAML config.

    Parameters
    ----------
    data_path : str
        Corpus text file: one ``<bos> ... <sep> ... <eos>`` sequence per line.
    vocab_path : str
        ``vocab.json`` written by ``TokenizerPipeline.save_vocab()``.
    seq_length : int
        Context window; longer lines are truncated, shorter ones padded.
    loss_ignore_tokens : list of str, optional
        Tokens kept as input but excluded from the loss, e.g. ``["<sep>"]``.
    objective : "clm" | "mlm"
        ``"mlm"`` returns a :class:`BankMLMDataset` (masked-token prediction)
        with ``mask_token_id`` (required), ``mask_prob``, ``mask_unit`` and
        ``mask_seed``; src/train_decoder.py passes them from ``mlm:``.
    """
    if objective not in ("clm", "mlm"):
        raise ValueError(f"objective={objective!r}; choose 'clm' or 'mlm'")
    if objective == "mlm" and mask_token_id is None:
        raise ValueError("objective='mlm' needs mask_token_id")
    tokenizer = VocabTokenizer.from_file(vocab_path)
    ignore_ids = []
    for token in loss_ignore_tokens or ():
        if token not in tokenizer.vocab:
            raise ValueError(
                f"loss_ignore_tokens names {token!r}, which is not in {vocab_path}."
            )
        ignore_ids.append(tokenizer.vocab[token])
    if ignore_ids:
        print(f"  Excluded from the loss: {list(loss_ignore_tokens)} (still in the input)")
    data_path = Path(data_path)
    print(f"Loading corpus from {data_path} (vocab_size={tokenizer.vocab_size})...")

    sequences = []
    truncated = 0
    unknown = 0
    total = 0
    with open(data_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            ids = tokenizer.encode(line)
            unknown += ids.count(tokenizer.unk_token_id)
            total += len(ids)
            if len(ids) > seq_length:
                truncated += 1
                ids = ids[:seq_length]
            sequences.append(ids)

    print(f"  Loaded {len(sequences):,} sequences (seq_length={seq_length})")
    if truncated:
        print(f"  WARNING: {truncated:,} sequences exceeded seq_length and were truncated")
    if unknown:
        # A corpus and vocabulary from different fits still trains, and produces
        # meaningless embeddings -- fail loudly instead.
        raise ValueError(
            f"{unknown:,} of {total:,} corpus tokens are not in {vocab_path}. "
            "The corpus and the vocabulary come from different tokenizer fits; "
            "regenerate both (notebook 02 / scripts/build_bank_corpus.py)."
        )

    if objective == "mlm":
        special = [tokenizer.vocab[t] for t in ("<pad>", "<bos>", "<eos>", "<sep>", "<unk>")
                   if t in tokenizer.vocab]
        return BankMLMDataset(
            sequences=sequences,
            seq_length=seq_length,
            pad_token_id=tokenizer.pad_token_id,
            loss_ignore_ids=ignore_ids,
            mask_token_id=mask_token_id,
            special_ids=special,
            vocab_size=tokenizer.vocab_size,
            sep_token_id=tokenizer.sep_token_id,
            mask_prob=mask_prob,
            mask_unit=mask_unit,
            mask_seed=mask_seed,
        )
    return FinancialCLMDataset(
        sequences=sequences,
        seq_length=seq_length,
        pad_token_id=tokenizer.pad_token_id,
        loss_ignore_ids=ignore_ids,
    )
